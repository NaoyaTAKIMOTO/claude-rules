#!/bin/bash
set -e
mkdir -p "$HOME/.claude"
cat > "$HOME/.claude/CLAUDE.md" <<'CLAUDE_MD_EOF'
# 共通作業ルール

## 適用範囲
- コードを変える作業に適用する
- 質問への回答や調べものだけのときは、計画の合意などの手順を省いてよい
- リポジトリの CLAUDE.md と食い違うときは、どちらかを勝手に選ばずユーザーに確認する

## 目的の整理
- 議論では目的を大目的・中目的・小目的に分けて整理し、計画書の冒頭に書く
- 判断が分かれたら、常により上位の目的を優先する

## 計画と合意
- 計画を立てる前に先行事例とベストプラクティスを調べ、出典を計画書に残す
- 計画は docs/plans/YYYY-MM-DD-<テーマ>.md に書く
- 実装に着手する前に、計画についてユーザーと合意する。合意前にコードを書かない
- 進捗は計画書のチェックリストで適宜更新する
- 独立した調査や作業はサブエージェントに並行して任せ、結果は自分で確かめてから使う

## 記録
- 判断の根拠、失敗、試行錯誤は docs/log.md に日付つきで追記する
- 全体像・実装の進捗・課題を図解した docs/status.html を作り、進捗に合わせて更新する
- プラグイン(superpowers など)が別の置き場所を指定しても、上の置き場所に揃える

## テストとコミット
- テストファーストで進める: テストを書く → 実行して失敗を確認 → 実装 → 全テストが通る
- テストを書いて実行したら、失敗したときの出力を計画書の進捗欄に貼る
- テスト(単体・結合)が通っていない状態ではコミットしない。feat ブランチでも同じ
- 実装中に既存のテストを緩めない。変更が必要なら手を止め、理由を伝えて承認を得る

## 動作確認
- ユーザーに動作確認を頼むときは、スクショ・動画・音声など必要なものを用意して渡す
- 動画や音声は容量が大きいので git に入れず(.gitignore)、ファイルとして直接送る

## ブランチと e2e
- ブランチは main / dev / feat/<テーマ> で運用する
- 作業は feat で行い、PR で dev へ、dev から main へ進める
- main と dev へは、e2e が通らないとマージしない
- dev / main へのマージは、ユーザーの承認を得てから行う
- e2e は GitHub Actions かユーザーの Mac で実行する。クラウドのコンテナ内では完結させない
- リポジトリで作業を始めるとき、次がなければ整える
  - dev ブランチ
  - 単体・結合テストと e2e を実行する GitHub Actions のワークフロー
  - main / dev へのブランチ保護(e2e が通らないとマージできない設定)
- ブランチ保護が使えないとき(無料プランの非公開リポジトリなど)はユーザーに伝え、運用で守る

## デプロイ時点(dev → main へのマージ直前)
次の順で行う。リファクタリングは必ず e2e より前に終える。
1. dev 上でリファクタリング(重複排除、ロジックの単純化、定数の切り出しなど)
2. セキュリティチェック(依存の脆弱性、秘密情報の混入、認証や入力検証の不備)
3. 単体・結合テストと e2e が通ることを確認する
4. ユーザーの承認を得て main へマージする
CLAUDE_MD_EOF
